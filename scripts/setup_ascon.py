#!/usr/bin/env python3
"""Fetch the Ascon reference implementation and its official test vectors.

What this script does
---------------------
1. Clones ``https://github.com/meichlseder/pyascon`` (the Python reference
   implementation, CC0-1.0) into a temporary directory and copies ``ascon.py``
   into ``third_party/pyascon/``.
2. Clones ``https://github.com/ascon/ascon-c`` (the Ascon team's official C
   reference implementation, CC0-1.0) and copies
   ``crypto_aead/asconaead128/LWC_AEAD_KAT_128_128.txt`` into
   ``third_party/ascon_kat/``.
3. Writes ``third_party/PROVENANCE.json`` recording the exact commit hash,
   fetch date and SHA-256 of every file copied.

Why two repositories
--------------------
The Python file is what the experiment runs.  The KAT file is what proves the
Python file conforms to NIST SP 800-232 -- and a conformance check is only
meaningful if the vectors come from an *independent* implementation.  Checking
pyascon against vectors generated by pyascon would prove nothing.

Why record the commit hash
--------------------------
"We used pyascon" is not reproducible; "we used pyascon at commit ed24e54"
is.  ``PROVENANCE.json`` is read back by ``src/environment_info.py`` and lands
in ``results/environment.json``, so every set of results carries the identity
of the code that produced it.

Usage::

    python scripts/setup_ascon.py            # fetch (skips if already present)
    python scripts/setup_ascon.py --force    # re-fetch and overwrite
    python scripts/setup_ascon.py --check    # verify what is installed

If your network blocks git, run with ``--manual`` for copy-paste instructions.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
THIRD_PARTY = PROJECT_ROOT / "third_party"
PYASCON_DIR = THIRD_PARTY / "pyascon"
KAT_DIR = THIRD_PARTY / "ascon_kat"
PROVENANCE = THIRD_PARTY / "PROVENANCE.json"

PYASCON_URL = "https://github.com/meichlseder/pyascon.git"
ASCON_C_URL = "https://github.com/ascon/ascon-c.git"
KAT_RELATIVE = Path("crypto_aead/asconaead128/LWC_AEAD_KAT_128_128.txt")

MANUAL_INSTRUCTIONS = f"""
Manual setup (if `git clone` is unavailable here)
=================================================
Run these from the project root. Both repositories are CC0-1.0 licensed.

  git clone https://github.com/meichlseder/pyascon.git  temp_pyascon
  git clone https://github.com/ascon/ascon-c.git        temp_asconc

Then copy two files:

  Windows (PowerShell / cmd):
    mkdir third_party\\pyascon
    mkdir third_party\\ascon_kat
    copy temp_pyascon\\ascon.py third_party\\pyascon\\ascon.py
    copy temp_asconc\\{str(KAT_RELATIVE).replace('/', chr(92))} third_party\\ascon_kat\\

  macOS / Linux:
    mkdir -p third_party/pyascon third_party/ascon_kat
    cp temp_pyascon/ascon.py third_party/pyascon/ascon.py
    cp temp_asconc/{KAT_RELATIVE} third_party/ascon_kat/

Record the commits so your results are reproducible:

  git -C temp_pyascon rev-parse HEAD
  git -C temp_asconc  rev-parse HEAD

and put them into third_party/PROVENANCE.json, then delete the temp clones.
Finally verify with:  python scripts/setup_ascon.py --check
"""


def sha256_of(path: Path) -> str:
    """Return the hex SHA-256 of a file."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run_git(args: list[str], cwd: Path | None = None) -> str:
    """Run a git command and return its stripped stdout.

    Raises:
        RuntimeError: with a readable message if git fails or is missing.
    """
    try:
        completed = subprocess.run(
            ["git", *args],
            cwd=str(cwd) if cwd else None,
            check=True,
            capture_output=True,
            text=True,
        )
    except FileNotFoundError as exc:
        raise RuntimeError(
            "git was not found on PATH. Install Git for Windows from "
            "https://git-scm.com/download/win, or run with --manual."
        ) from exc
    except subprocess.CalledProcessError as exc:
        raise RuntimeError(
            f"git {' '.join(args)} failed:\n{exc.stderr.strip()}"
        ) from exc
    return completed.stdout.strip()


def fetch(force: bool = False) -> dict[str, object]:
    """Clone both repositories and vendor the two files we need."""
    THIRD_PARTY.mkdir(parents=True, exist_ok=True)
    PYASCON_DIR.mkdir(parents=True, exist_ok=True)
    KAT_DIR.mkdir(parents=True, exist_ok=True)

    ascon_target = PYASCON_DIR / "ascon.py"
    kat_target = KAT_DIR / KAT_RELATIVE.name

    if ascon_target.is_file() and kat_target.is_file() and not force:
        print("Both files are already present. Use --force to re-fetch.")
        return load_provenance()

    record: dict[str, object] = {
        "fetched_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "sources": {},
    }

    with tempfile.TemporaryDirectory(prefix="ascon_setup_") as tmpdir:
        temp = Path(tmpdir)

        # ---- 1. pyascon: the implementation the experiment runs ----------
        print(f"Cloning {PYASCON_URL} ...")
        pyascon_clone = temp / "pyascon"
        run_git(["clone", "--depth", "1", PYASCON_URL, str(pyascon_clone)])
        commit = run_git(["rev-parse", "HEAD"], cwd=pyascon_clone)
        commit_date = run_git(
            ["log", "-1", "--format=%cd", "--date=iso"], cwd=pyascon_clone
        )
        shutil.copy2(pyascon_clone / "ascon.py", ascon_target)
        for extra in ("LICENSE", "README.md"):
            source = pyascon_clone / extra
            if source.is_file():
                shutil.copy2(source, PYASCON_DIR / extra)
        record["sources"]["pyascon"] = {
            "role": "Ascon-AEAD128 implementation used by the experiment",
            "url": PYASCON_URL.removesuffix(".git"),
            "commit": commit,
            "commit_date": commit_date,
            "license": "CC0-1.0",
            "author": "Maria Eichlseder (Ascon co-designer)",
            "vendored_file": str(ascon_target.relative_to(PROJECT_ROOT)),
            "sha256": sha256_of(ascon_target),
        }
        print(f"  pyascon @ {commit[:12]} ({commit_date})")

        # ---- 2. ascon-c: the independent source of KAT vectors -----------
        print(f"Cloning {ASCON_C_URL} ...")
        asconc_clone = temp / "ascon-c"
        run_git(["clone", "--depth", "1", ASCON_C_URL, str(asconc_clone)])
        c_commit = run_git(["rev-parse", "HEAD"], cwd=asconc_clone)
        c_commit_date = run_git(
            ["log", "-1", "--format=%cd", "--date=iso"], cwd=asconc_clone
        )
        source_kat = asconc_clone / KAT_RELATIVE
        if not source_kat.is_file():
            raise RuntimeError(
                f"Expected KAT file not found at {KAT_RELATIVE} in ascon-c. "
                "The upstream layout may have changed; see --manual."
            )
        shutil.copy2(source_kat, kat_target)
        record["sources"]["ascon-c"] = {
            "role": "Official known-answer test vectors for conformance checking",
            "url": ASCON_C_URL.removesuffix(".git"),
            "commit": c_commit,
            "commit_date": c_commit_date,
            "license": "CC0-1.0",
            "author": "The Ascon team",
            "vendored_file": str(kat_target.relative_to(PROJECT_ROOT)),
            "upstream_path": str(KAT_RELATIVE),
            "sha256": sha256_of(kat_target),
        }
        print(f"  ascon-c @ {c_commit[:12]} ({c_commit_date})")

    PROVENANCE.write_text(json.dumps(record, indent=2), encoding="utf-8")
    print(f"\nWrote provenance to {PROVENANCE.relative_to(PROJECT_ROOT)}")
    return record


def load_provenance() -> dict[str, object]:
    """Read PROVENANCE.json, or an empty dict if absent."""
    if not PROVENANCE.is_file():
        return {}
    try:
        return json.loads(PROVENANCE.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}


def check() -> int:
    """Verify the installation and run a conformance smoke test.

    Returns a process exit code: 0 on success, 1 on failure.
    """
    sys.path.insert(0, str(PROJECT_ROOT))
    problems: list[str] = []

    ascon_target = PYASCON_DIR / "ascon.py"
    kat_target = KAT_DIR / KAT_RELATIVE.name

    print("Checking Ascon installation")
    print("-" * 60)
    print(f"Implementation : {'OK' if ascon_target.is_file() else 'MISSING'}  {ascon_target}")
    print(f"KAT vectors    : {'OK' if kat_target.is_file() else 'MISSING'}  {kat_target}")

    if not ascon_target.is_file():
        problems.append("ascon.py is missing. Run: python scripts/setup_ascon.py")
    if not kat_target.is_file():
        problems.append("KAT file is missing. Run: python scripts/setup_ascon.py")

    provenance = load_provenance()
    if provenance:
        for name, info in provenance.get("sources", {}).items():
            print(f"{name:<15}: commit {str(info.get('commit'))[:12]}  ({info.get('license')})")
    else:
        problems.append("PROVENANCE.json missing; results will not be reproducible.")

    if not problems:
        try:
            from src.kat import run_kat  # noqa: PLC0415  (import after sys.path fix)

            report = run_kat()
            status = "PASS" if report.passed else "FAIL"
            print(
                f"\nConformance    : {status} "
                f"({report.encrypt_matches}/{report.total} encrypt, "
                f"{report.decrypt_matches}/{report.total} decrypt)"
            )
            if not report.passed:
                problems.append(
                    f"KAT failures at Count = {report.failures[:10]}. "
                    "The implementation does not conform to the vectors."
                )
        except Exception as exc:  # noqa: BLE001 - report anything that goes wrong
            problems.append(f"Conformance check could not run: {type(exc).__name__}: {exc}")

    if problems:
        print("\nProblems found:")
        for problem in problems:
            print(f"  - {problem}")
        return 1
    print("\nAll checks passed. The project is using NIST SP 800-232 Ascon-AEAD128.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Fetch and verify the Ascon reference implementation.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--force", action="store_true", help="re-fetch and overwrite")
    parser.add_argument("--check", action="store_true", help="verify what is installed")
    parser.add_argument("--manual", action="store_true", help="print manual instructions")
    args = parser.parse_args()

    if args.manual:
        print(MANUAL_INSTRUCTIONS)
        return 0
    if args.check:
        return check()

    try:
        fetch(force=args.force)
    except RuntimeError as exc:
        print(f"\nSetup failed: {exc}", file=sys.stderr)
        print(MANUAL_INSTRUCTIONS, file=sys.stderr)
        return 1
    return check()


if __name__ == "__main__":
    raise SystemExit(main())
